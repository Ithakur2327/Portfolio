// Regenerates app/breakpoints.generated.css from lib/breakpoints.json.
//
// This runs automatically before every `next dev` and `next build`
// (see the "predev" / "prebuild" scripts in package.json), so
// globals.css always sees the current breakpoint scale without anyone
// needing to hand-edit two files. Don't edit the generated CSS file —
// change lib/breakpoints.json and re-run `npm run dev` / `npm run build`.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const jsonPath = path.join(__dirname, "..", "lib", "breakpoints.json");
const outPath = path.join(__dirname, "..", "app", "breakpoints.generated.css");

const bp = JSON.parse(readFileSync(jsonPath, "utf-8"));

const css = `/* ═══════════════════════════════════════════════════════════════
   AUTO-GENERATED — DO NOT EDIT BY HAND.
   Source: lib/breakpoints.json
   Regenerated by: scripts/generate-breakpoints-css.mjs
   (runs automatically via the "predev"/"prebuild" npm scripts)

   Every @media rule in globals.css should use one of the named
   conditions below instead of a raw pixel number, so the entire
   file's responsiveness is controlled from lib/breakpoints.json.
═══════════════════════════════════════════════════════════════ */

/* sub-mobile refinement tiers */
@custom-media --mobile-tiny (max-width: ${bp.mobileTinyMax}px);
@custom-media --mobile-xxs (min-width: ${bp.mobileTinyMax + 1}px) and (max-width: ${bp.mobileXxsMax}px);
@custom-media --mobile-xs (min-width: ${bp.mobileXxsMax + 1}px) and (max-width: ${bp.mobileXsMax}px);
@custom-media --mobile-sm (min-width: ${bp.mobileXsMax + 1}px) and (max-width: ${bp.mobileSmMax}px);

/* primary tiers */
@custom-media --mobile (max-width: ${bp.mobileMax}px);
@custom-media --nav-tiny (max-width: ${bp.navTinyMax}px);
@custom-media --tablet (min-width: ${bp.tabletMin}px) and (max-width: ${bp.tabletMax}px);
@custom-media --tablet-up (min-width: ${bp.tabletMin}px);
@custom-media --tablet-down (max-width: ${bp.tabletMax}px);
@custom-media --tablet-split-down (max-width: ${bp.tabletSplitMax}px);
@custom-media --tablet-split-up (min-width: ${bp.tabletSplitMin}px);

/* nav's own collapse/expansion points — deliberately separate, coarser
   thresholds than the content-level tablet/laptop split */
@custom-media --nav-roomy (min-width: ${bp.tabletSplitMin}px) and (max-width: ${bp.navRoomyMax}px);
@custom-media --nav-collapse (max-width: ${bp.navCollapseMax}px);
@custom-media --nav-expanded (min-width: ${bp.navCollapseMax + 1}px);

@custom-media --laptop (min-width: ${bp.laptopMin}px) and (max-width: ${bp.laptopWideMax}px);
@custom-media --laptop-narrow (min-width: ${bp.laptopMin}px) and (max-width: ${bp.laptopNarrowMax}px);
@custom-media --laptop-wide (min-width: ${bp.laptopWideMin}px) and (max-width: ${bp.laptopWideMax}px);
@custom-media --laptop-up (min-width: ${bp.laptopMin}px);
@custom-media --laptop-down (max-width: ${bp.laptopWideMax}px);

@custom-media --desktop (min-width: ${bp.desktopMin}px);

/* one-off wide-layout tiers */
@custom-media --content-wide-up (min-width: ${bp.contentWideMin}px);
@custom-media --wide-grid-up (min-width: ${bp.wideGridMin}px);
`;

writeFileSync(outPath, css, "utf-8");
console.log(`[breakpoints] generated ${path.relative(process.cwd(), outPath)} from lib/breakpoints.json`);
